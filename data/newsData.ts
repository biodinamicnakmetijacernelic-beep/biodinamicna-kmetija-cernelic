export function isEventPost(item: NewsItem): boolean {
  if (item.isEvent) return true;
  if (item.category && item.category.toLowerCase().includes('dogod')) return true;
  const title = (item.title || '').toLowerCase();
  const slug = (item.slug || '').toLowerCase();
  return (
    title.includes('vabilo') ||
    title.includes('usposabljanje') ||
    title.includes('izobraževanje') ||
    title.includes('ekskurzija') ||
    title.includes('delavnica') ||
    slug.includes('usposabljanje') ||
    slug.includes('izobraževanje') ||
    slug.includes('ekskurzija')
  );
}

export function mergeNewsWithStatic(sanityPosts: NewsItem[]): NewsItem[] {
  const map = new Map<string, NewsItem>();

  // Add sanity posts first
  for (const post of sanityPosts) {
    if (post && post.slug) {
      map.set(post.slug, post);
    }
  }

  // Merge static posts (if not already existing in sanity with the same slug)
  for (const staticItem of STATIC_NEWS) {
    if (!map.has(staticItem.slug)) {
      map.set(staticItem.slug, staticItem);
    }
  }

  // Convert to array and sort by publishedAt descending
  const merged = Array.from(map.values());
  merged.sort((a, b) => {
    const timeA = new Date(a.publishedAt).getTime();
    const timeB = new Date(b.publishedAt).getTime();
    return timeB - timeA;
  });

  return merged;
}
